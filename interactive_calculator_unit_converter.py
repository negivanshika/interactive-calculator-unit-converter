# Interactive Calculator & Unit Converter
# InternCircle - Task 2


# Function for getting a valid number
def get_number(message):
    while True:
        try:
            return float(input(message))
        except ValueError:
            print("Invalid input! Please enter a number.")


# Basic arithmetic
def arithmetic():
    print("\n--- Basic Arithmetic ---")

    num1 = get_number("Enter first number: ")
    num2 = get_number("Enter second number: ")

    while True:
        print("\nChoose an operation:")
        print("1. Addition (+)")
        print("2. Subtraction (-)")
        print("3. Multiplication (*)")
        print("4. Division (/)")

        choice = input("Enter your choice (1-4): ")

        if choice == "1":
            print("Result:", num1 + num2)
            break

        elif choice == "2":
            print("Result:", num1 - num2)
            break

        elif choice == "3":
            print("Result:", num1 * num2)
            break

        elif choice == "4":
            if num2 == 0:
                print("Cannot divide by zero!")
            else:
                print("Result:", num1 / num2)
                break

        else:
            print("Invalid choice! Please choose 1-4.")


# Unit conversion
def unit_conversion():
    print("\n--- Unit Conversion ---")

    while True:
        print("\n1. Kilometres to Miles")
        print("2. Celsius to Fahrenheit")
        print("3. Back to Main Menu")

        choice = input("Enter your choice (1-3): ")

        if choice == "1":
            km = get_number("Enter distance in kilometres: ")
            miles = km * 0.621371
            print(f"{km} km = {miles:.2f} miles")

        elif choice == "2":
            celsius = get_number("Enter temperature in Celsius: ")
            fahrenheit = (celsius * 9 / 5) + 32
            print(f"{celsius}°C = {fahrenheit:.2f}°F")

        elif choice == "3":
            break

        else:
            print("Invalid choice! Please choose 1-3.")


# Currency conversion
def currency_conversion():
    print("\n--- Currency Conversion ---")
    print("INR to USD")

    while True:
        inr = get_number("Enter amount in INR: ")

        if inr < 0:
            print("Amount cannot be negative.")
            continue

        # Enter the current exchange rate manually
        rate = get_number("Enter INR value of 1 USD: ")

        if rate <= 0:
            print("Exchange rate must be greater than 0.")
            continue

        usd = inr / rate

        print(f"₹{inr:.2f} = ${usd:.2f}")
        break


# Main program
def main():
    print("======================================")
    print("  INTERACTIVE CALCULATOR & CONVERTER")
    print("======================================")

    while True:
        print("\n========== MAIN MENU ==========")
        print("1. Basic Arithmetic")
        print("2. Unit Conversion")
        print("3. Currency Conversion")
        print("4. Exit")
        print("===============================")

        choice = input("Enter your choice (1-4): ")

        if choice == "1":
            arithmetic()

        elif choice == "2":
            unit_conversion()

        elif choice == "3":
            currency_conversion()

        elif choice == "4":
            print("\nThank you for using the program!")
            break

        else:
            print("Invalid choice! Please enter 1-4.")


# Start the program
main()